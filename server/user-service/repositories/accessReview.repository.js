import { one, pool, query } from '../utils/index.js'

// Every database read and write for access review (user) reports (Laravel's AccessReviewRepository)

const WITH_PEOPLE = `select r.id, r.period_start, r.period_end, r.period_type, r.scheduled, r.summary, r.reviewed_at, r.review_note, r.created_at,
    g.full_name as generator_name, v.full_name as reviewer_name`
const FROM = `from access_reviews r
  left join users g on g.id = r.generated_by
  left join users v on v.id = r.reviewed_by`

/** The newest reports (without their row tables), with who generated and reviewed them */
export const latest = (limit = 50) => query(`${WITH_PEOPLE} ${FROM} order by r.id desc limit $1`, [limit])

/** One report with its full row table */
export const findWithPeople = (id, client = pool) => one(`${WITH_PEOPLE}, r.rows ${FROM} where r.id = $1`, [id], client)

export const find = (id) => one('select id, period_type, period_start, period_end from access_reviews where id = $1', [id])

export async function create(client, { periodStart, periodEnd, periodType, scheduled, generatedBy, summary, rows }) {
  return one(
    `insert into access_reviews (period_start, period_end, period_type, scheduled, generated_by, summary, rows, created_at, updated_at)
     values ($1, $2, $3, $4, $5, $6, $7, now(), now()) returning id`,
    [periodStart, periodEnd, periodType, scheduled, generatedBy, JSON.stringify(summary), JSON.stringify(rows)],
    client,
  )
}

/** Deletes the reports generated by hand for exactly this period (dates 'YYYY-MM-DD'); returns their ids */
export async function deleteManualFor(client, type, startDate, endDate) {
  const rows = await query(
    'delete from access_reviews where scheduled = false and period_type = $1 and period_start = $2 and period_end = $3 returning id',
    [type, startDate, endDate],
    client,
  )
  return rows.map((row) => row.id).sort((a, b) => a - b)
}

/** Whether the schedule already made a report for this period */
export async function scheduledExists(type, startDate, endDate, client = pool) {
  return Boolean(
    await one('select 1 from access_reviews where scheduled = true and period_type = $1 and period_start = $2 and period_end = $3 limit 1', [type, startDate, endDate], client),
  )
}

export const remove = (id) => query('delete from access_reviews where id = $1', [id])
